
from pathlib import Path
import sys
import joblib
import pandas as pd
import streamlit as st
import matplotlib.pyplot as plt
import seaborn as sns
import sklearn

from sklearn.metrics import (
    accuracy_score,
    roc_auc_score,
    precision_score,
    recall_score,
    f1_score,
    matthews_corrcoef,
    confusion_matrix,
    classification_report
)

# --------------------------------------------------
# 1. STREAMLIT CONFIGURATION
# --------------------------------------------------

st.set_page_config(
    page_title="Bank Marketing | ML Model Lab",
    page_icon="📈",
    layout="wide"
)

# --------------------------------------------------
# 2. PROJECT INFORMATION
# --------------------------------------------------

st.title("Bank Marketing — Subscription Prediction")

st.caption(
    "BITS Pilani M.Tech (DSE) | Machine Learning Assignment 2"
)

st.markdown(
    """
    This interactive application compares five machine learning
    classification models using the UCI Bank Marketing dataset.

    Upload the test CSV generated by the notebook to evaluate
    the selected model.
    """
)

# --------------------------------------------------
# 3. ENVIRONMENT INFORMATION
# --------------------------------------------------

with st.expander("Environment Information"):

    st.write("Python:", sys.version)
    st.write("Scikit-learn:", sklearn.__version__)
    st.write("Pandas:", pd.__version__)

# --------------------------------------------------
# 4. PROJECT PATHS
# --------------------------------------------------

ROOT = Path(__file__).resolve().parent

MODEL_DIR = ROOT / "model"

MODEL_FILES = {
    "Logistic Regression": "logistic_regression.pkl",
    "Decision Tree": "decision_tree.pkl",
    "K-Nearest Neighbors": "knn.pkl",
    "Gaussian Naive Bayes": "naive_bayes.pkl",
    "Support Vector Machine": "support_vector_machine.pkl"
}

# --------------------------------------------------
# 5. CHECK MODEL FILES
# --------------------------------------------------

available = {}

for model_name, filename in MODEL_FILES.items():

    model_path = MODEL_DIR / filename

    if model_path.exists():
        available[model_name] = model_path

if len(available) != 5:

    missing_models = [
        name for name in MODEL_FILES
        if name not in available
    ]

    st.error("Some trained model files are missing.")

    st.write("Missing models:", missing_models)

    st.info(
        "Please check the model folder and run the notebook "
        "model-saving cell if necessary."
    )

    st.stop()

# --------------------------------------------------
# 6. SIDEBAR SETTINGS
# --------------------------------------------------

with st.sidebar:

    st.header("Evaluation Settings")

    selected_model = st.selectbox(
        "Select Classifier",
        list(MODEL_FILES.keys())
    )

    uploaded_file = st.file_uploader(
        "Upload Test CSV",
        type=["csv"]
    )

    st.caption(
        "Upload test_data.csv containing predictor columns "
        "and target column y."
    )

# --------------------------------------------------
# 7. LOAD TEST DATA
# --------------------------------------------------

if uploaded_file is not None:

    try:
        test_df = pd.read_csv(uploaded_file)

    except Exception as exc:

        st.error(f"Could not read uploaded CSV: {exc}")
        st.stop()

else:

    default_test = ROOT / "test_data.csv"

    if default_test.exists():

        st.info(
            "No file uploaded. Using the project's test_data.csv."
        )

        test_df = pd.read_csv(default_test)

    else:

        st.warning(
            "Please upload test_data.csv generated from the notebook."
        )

        st.stop()

# --------------------------------------------------
# 8. VALIDATE TEST DATA
# --------------------------------------------------

if "y" not in test_df.columns:

    st.error(
        "Required target column 'y' is missing from the CSV."
    )

    st.stop()

X_test = test_df.drop(
    columns=["y", "duration"],
    errors="ignore"
)

y_test = (
    test_df["y"]
    .astype(str)
    .str.strip()
    .str.lower()
    .map({"no": 0, "yes": 1})
)

if y_test.isna().any():

    st.error(
        "Target column y must contain only 'yes' or 'no'."
    )

    st.stop()

if X_test.empty:

    st.error("No predictor columns found.")

    st.stop()

if y_test.nunique() != 2:

    st.error(
        "The test dataset must contain both target classes: yes and no."
    )

    st.stop()

# --------------------------------------------------
# 9. LOAD SELECTED MODEL
# --------------------------------------------------

st.divider()

st.subheader(f"Selected Model: {selected_model}")

try:

    model_path = available[selected_model]

    model = joblib.load(model_path)

    # Decision Tree compatibility correction
    # for models saved using an older scikit-learn version

    if selected_model == "Decision Tree":

        if hasattr(model, "named_steps"):

            tree_classifier = model.named_steps["classifier"]

            if not hasattr(tree_classifier, "monotonic_cst"):

                tree_classifier.monotonic_cst = None

    st.success(
        f"{selected_model} loaded successfully."
    )

except Exception as exc:

    st.error(
        f"Model loading failed: {exc}"
    )

    st.exception(exc)

    st.stop()

# --------------------------------------------------
# 10. MAKE PREDICTIONS
# --------------------------------------------------

try:

    y_pred = model.predict(X_test)

    if not hasattr(model, "predict_proba"):

        st.error(
            "Selected model does not support probability predictions."
        )

        st.stop()

    y_score_all = model.predict_proba(X_test)

    # Identify positive class

    if hasattr(model, "classes_"):

        classes = list(model.classes_)

    else:

        st.error("Model classes could not be identified.")

        st.stop()

    if 1 in classes:

        positive_index = classes.index(1)

    elif "yes" in classes:

        positive_index = classes.index("yes")

    else:

        st.error(
            "Positive target class could not be identified."
        )

        st.stop()

    y_score = y_score_all[:, positive_index]

    st.success(
        f"{selected_model} predictions generated successfully."
    )

except Exception as exc:

    st.error(
        f"Prediction failed for {selected_model}: {exc}"
    )

    st.exception(exc)

    st.stop()

# --------------------------------------------------
# 11. CALCULATE EVALUATION METRICS
# --------------------------------------------------

try:

    metric_values = {

        "Accuracy": accuracy_score(
            y_test,
            y_pred
        ),

        "AUC": roc_auc_score(
            y_test,
            y_score
        ),

        "Precision": precision_score(
            y_test,
            y_pred,
            zero_division=0
        ),

        "Recall": recall_score(
            y_test,
            y_pred,
            zero_division=0
        ),

        "F1": f1_score(
            y_test,
            y_pred,
            zero_division=0
        ),

        "MCC": matthews_corrcoef(
            y_test,
            y_pred
        )
    }

except Exception as exc:

    st.error(
        f"Metric calculation failed: {exc}"
    )

    st.exception(exc)

    st.stop()

# --------------------------------------------------
# 12. DISPLAY METRICS
# --------------------------------------------------

st.divider()

st.subheader("Model Evaluation Results")

cols = st.columns(6)

for col, (label, value) in zip(
    cols,
    metric_values.items()
):

    col.metric(
        label,
        f"{value:.4f}"
    )

# --------------------------------------------------
# 13. CONFUSION MATRIX
# --------------------------------------------------

left, right = st.columns(2)

with left:

    st.subheader("Confusion Matrix")

    matrix = confusion_matrix(
        y_test,
        y_pred,
        labels=[0, 1]
    )

    fig, ax = plt.subplots(
        figsize=(5, 4)
    )

    sns.heatmap(
        matrix,
        annot=True,
        fmt="d",
        cmap="Blues",
        xticklabels=["No", "Yes"],
        yticklabels=["No", "Yes"],
        ax=ax
    )

    ax.set_xlabel("Predicted")
    ax.set_ylabel("Actual")
    ax.set_title(selected_model)

    st.pyplot(fig)

    plt.close(fig)

# --------------------------------------------------
# 14. CLASSIFICATION REPORT
# --------------------------------------------------

with right:

    st.subheader("Classification Report")

    report = classification_report(
        y_test,
        y_pred,
        labels=[0, 1],
        target_names=["no", "yes"],
        output_dict=True,
        zero_division=0
    )

    report_df = pd.DataFrame(
        report
    ).transpose().round(4)

    st.dataframe(
        report_df,
        use_container_width=True
    )

# --------------------------------------------------
# 15. TEST DATA PREVIEW
# --------------------------------------------------

st.divider()

st.subheader("Test Data Preview")

st.write(
    f"Total rows evaluated: **{len(test_df):,}**"
)

st.dataframe(
    test_df.head(10),
    use_container_width=True
)

# --------------------------------------------------
# 16. COMPLETION MESSAGE
# --------------------------------------------------

st.divider()

st.success(
    f"{selected_model} evaluation completed successfully!"
)
