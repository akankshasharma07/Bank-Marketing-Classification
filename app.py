
from pathlib import Path
import sys
import joblib
import pandas as pd
import streamlit as st
import matplotlib.pyplot as plt
import seaborn as sns
import sklearn

from sklearn.metrics import (
    accuracy_score,
    roc_auc_score,
    precision_score,
    recall_score,
    f1_score,
    matthews_corrcoef,
    confusion_matrix,
    classification_report
)


# --------------------------------------------------
# 1. PAGE CONFIGURATION
# --------------------------------------------------

st.set_page_config(
    page_title="Bank Marketing Classification",
    page_icon="📊",
    layout="wide"
)

st.title("Bank Marketing — Subscription Prediction")

st.write(
    "BITS Pilani M.Tech (DSE) | Machine Learning Assignment 2"
)

st.write(
    "This interactive application compares five machine learning "
    "classification models using the UCI Bank Marketing dataset."
)

st.write(
    "Upload the test CSV generated by the notebook to evaluate "
    "the selected model."
)


# --------------------------------------------------
# 2. PROJECT PATHS
# --------------------------------------------------

ROOT = Path(__file__).resolve().parent
MODEL_DIR = ROOT / "model"


# --------------------------------------------------
# 3. MODEL FILES
# --------------------------------------------------

MODEL_FILES = {
    "Logistic Regression": "logistic_regression.pkl",
    "Decision Tree": "decision_tree.pkl",
    "K-Nearest Neighbors": "knn.pkl",
    "Gaussian Naive Bayes": "naive_bayes.pkl",
    "Support Vector Machine": "support_vector_machine.pkl"
}


# --------------------------------------------------
# 4. ENVIRONMENT INFORMATION
# --------------------------------------------------

st.subheader("Environment Information")

col1, col2, col3 = st.columns(3)

col1.metric("Python Version", sys.version.split()[0])
col2.metric("Scikit-learn", sklearn.__version__)
col3.metric("Pandas", pd.__version__)


# --------------------------------------------------
# 5. CHECK MODEL FILES
# --------------------------------------------------

available_models = {}

for model_name, filename in MODEL_FILES.items():

    model_path = MODEL_DIR / filename

    if model_path.exists():
        available_models[model_name] = model_path


if len(available_models) != 5:

    st.error("Some model files are missing.")

    st.write("Please check that your GitHub repository contains:")

    for filename in MODEL_FILES.values():
        st.write(f"- model/{filename}")

    st.stop()


# --------------------------------------------------
# 6. MODEL SELECTION
# --------------------------------------------------

st.subheader("Select Machine Learning Model")

selected_model = st.selectbox(
    "Choose a model for evaluation:",
    list(MODEL_FILES.keys())
)


# --------------------------------------------------
# 7. LOAD SELECTED MODEL
# --------------------------------------------------

model_path = available_models[selected_model]

try:

    model = joblib.load(model_path)

    # Compatibility fix for older Decision Tree pickle files
    if selected_model == "Decision Tree":

        if hasattr(model, "named_steps"):

            tree_classifier = model.named_steps.get("classifier")

            if (
                tree_classifier is not None
                and not hasattr(tree_classifier, "monotonic_cst")
            ):
                tree_classifier.monotonic_cst = None

except Exception as exc:

    st.error(f"Unable to load model: {exc}")
    st.stop()


# --------------------------------------------------
# 8. UPLOAD TEST CSV
# --------------------------------------------------

st.subheader("Upload Test Dataset")

uploaded_file = st.file_uploader(
    "Upload your test CSV file",
    type=["csv"]
)


# --------------------------------------------------
# 9. READ CSV FILE
# --------------------------------------------------

if uploaded_file is not None:

    try:

        test_df = pd.read_csv(
            uploaded_file,
            encoding="utf-8-sig"
        )

    except Exception as exc:

        st.error(f"Could not read uploaded CSV: {exc}")
        st.stop()

else:

    default_test = ROOT / "test_data.csv"

    if default_test.exists():

        test_df = pd.read_csv(
            default_test,
            encoding="utf-8-sig"
        )

        st.info("Using the default test_data.csv file.")

    else:

        st.info("Please upload your test CSV file to continue.")
        st.stop()


# --------------------------------------------------
# 10. CLEAN CSV COLUMN NAMES
# --------------------------------------------------

test_df.columns = (
    test_df.columns.astype(str)
    .str.replace("\ufeff", "", regex=False)
    .str.strip()
)


# --------------------------------------------------
# 11. CHECK TARGET COLUMN
# --------------------------------------------------

target_col = next(
    (
        column
        for column in test_df.columns
        if column.lower() == "y"
    ),
    None
)

if target_col is None:

    st.error("Required target column 'y' is missing.")

    st.write(
        "Columns detected in uploaded CSV:",
        test_df.columns.tolist()
    )

    st.stop()


if target_col != "y":

    test_df = test_df.rename(
        columns={target_col: "y"}
    )


# --------------------------------------------------
# 12. PREPARE TEST DATA
# --------------------------------------------------

X_test = test_df.drop(
    columns=["y", "duration"],
    errors="ignore"
)

y_raw = (
    test_df["y"]
    .astype(str)
    .str.strip()
    .str.lower()
)

y_test = y_raw.map({
    "no": 0,
    "yes": 1,
    "0": 0,
    "1": 1
})


if y_test.isna().any():

    st.error(
        "The target column contains values other than yes, no, 0 or 1."
    )

    st.write("Target values detected:", y_raw.unique().tolist())

    st.stop()


y_test = y_test.astype(int)


if X_test.empty:

    st.error("No predictor columns found in the CSV.")
    st.stop()


# --------------------------------------------------
# 13. DISPLAY DATA
# --------------------------------------------------

st.subheader("Test Dataset Preview")

st.write("Number of records:", len(test_df))

st.write("Number of predictor columns:", len(X_test.columns))

st.dataframe(test_df.head(10), use_container_width=True)


# --------------------------------------------------
# 14. MAKE PREDICTIONS
# --------------------------------------------------

st.subheader("Model Evaluation Results")

try:

    y_pred = model.predict(X_test)

    y_pred = pd.Series(y_pred).astype(int)

    y_probability = None

    if hasattr(model, "predict_proba"):

        probabilities = model.predict_proba(X_test)

        classes = list(model.classes_)

        if 1 in classes:

            positive_index = classes.index(1)

            y_probability = probabilities[:, positive_index]

    elif hasattr(model, "decision_function"):

        decision_scores = model.decision_function(X_test)

        y_probability = decision_scores

except Exception as exc:

    st.error(
        f"Prediction failed for {selected_model}: {exc}"
    )

    st.stop()


# --------------------------------------------------
# 15. CALCULATE EVALUATION METRICS
# --------------------------------------------------

accuracy = accuracy_score(y_test, y_pred)

precision = precision_score(
    y_test,
    y_pred,
    zero_division=0
)

recall = recall_score(
    y_test,
    y_pred,
    zero_division=0
)

f1 = f1_score(
    y_test,
    y_pred,
    zero_division=0
)

mcc = matthews_corrcoef(y_test, y_pred)

if y_probability is not None and len(set(y_test)) == 2:

    auc = roc_auc_score(y_test, y_probability)

else:

    auc = float("nan")


# --------------------------------------------------
# 16. DISPLAY METRICS
# --------------------------------------------------

st.subheader(f"{selected_model} — Performance Metrics")

col1, col2, col3 = st.columns(3)

col1.metric("Accuracy", f"{accuracy:.4f}")
col2.metric(
    "AUC",
    f"{auc:.4f}" if pd.notna(auc) else "N/A"
)
col3.metric("Precision", f"{precision:.4f}")

col4, col5, col6 = st.columns(3)

col4.metric("Recall", f"{recall:.4f}")
col5.metric("F1 Score", f"{f1:.4f}")
col6.metric("MCC", f"{mcc:.4f}")


# --------------------------------------------------
# 17. CONFUSION MATRIX
# --------------------------------------------------

st.subheader("Confusion Matrix")

cm = confusion_matrix(
    y_test,
    y_pred,
    labels=[0, 1]
)

fig, ax = plt.subplots(figsize=(6, 4))

sns.heatmap(
    cm,
    annot=True,
    fmt="d",
    cmap="Blues",
    xticklabels=["No", "Yes"],
    yticklabels=["No", "Yes"],
    ax=ax
)

ax.set_xlabel("Predicted Label")
ax.set_ylabel("Actual Label")
ax.set_title("Confusion Matrix")

st.pyplot(fig)

plt.close(fig)


# --------------------------------------------------
# 18. CLASSIFICATION REPORT
# --------------------------------------------------

st.subheader("Classification Report")

report = classification_report(
    y_test,
    y_pred,
    labels=[0, 1],
    target_names=["No", "Yes"],
    output_dict=True,
    zero_division=0
)

report_df = pd.DataFrame(report).transpose()

st.dataframe(
    report_df.round(4),
    use_container_width=True
)


# --------------------------------------------------
# 19. FINAL STATUS
# --------------------------------------------------

st.success(
    f"{selected_model} evaluation completed successfully!"
)
