from pathlib import Path
import joblib
import pandas as pd
import streamlit as st
import matplotlib.pyplot as plt
import seaborn as sns
from sklearn.metrics import (
    accuracy_score, roc_auc_score, precision_score, recall_score,
    f1_score, matthews_corrcoef, confusion_matrix, classification_report
)

ROOT = Path(__file__).resolve().parent
MODEL_DIR = ROOT / "model"
MODEL_FILES = {
    "Logistic Regression": "logistic_regression.pkl",
    "Decision Tree": "decision_tree.pkl",
    "K-Nearest Neighbors": "knn.pkl",
    "Gaussian Naive Bayes": "naive_bayes.pkl",
    "Support Vector Machine": "support_vector_machine.pkl",
}

st.set_page_config(page_title="Bank Marketing | ML Model Lab", page_icon="📈", layout="wide")
st.title("Bank Marketing — Subscription Prediction")
st.caption("BITS Pilani M.Tech (DSE) | Machine Learning Assignment 2")
st.markdown(
    "This interactive model lab compares five classifiers on the UCI Bank Marketing dataset. "
    "Upload the held-out test CSV generated by the notebook to calculate the evaluation metrics."
)

available = {name: MODEL_DIR / filename for name, filename in MODEL_FILES.items()
             if (MODEL_DIR / filename).exists()}
if len(available) != 5:
    st.error("One or more trained model files are missing. Run all cells in bank_marketing_classification.ipynb first.")
    st.stop()

with st.sidebar:
    st.header("Evaluation settings")
    selected_model = st.selectbox("Select classifier", list(available.keys()))
    uploaded_file = st.file_uploader("Upload test CSV", type=["csv"])
    st.caption("The CSV should contain the original predictor columns and target `y` (yes/no). Upload test data only.")

if uploaded_file is None:
    default_test = ROOT / "test_data.csv"
    if default_test.exists():
        st.info("No file uploaded. Using the project's generated test_data.csv.")
        test_df = pd.read_csv(default_test)
    else:
        st.warning("Upload test_data.csv after generating it from the notebook.")
        st.stop()
else:
    test_df = pd.read_csv(uploaded_file)

if "y" not in test_df.columns:
    st.error("Required target column `y` is missing.")
    st.stop()

X_test = test_df.drop(columns=["y", "duration"], errors="ignore")
y_test = test_df["y"].map({"no": 0, "yes": 1})
if y_test.isna().any():
    st.error("Target column `y` must contain only 'no' and 'yes'.")
    st.stop()

model = joblib.load(available[selected_model])
try:
    y_pred = model.predict(X_test)
    y_score = model.predict_proba(X_test)[:, 1]
except Exception as exc:
    st.error(f"Could not evaluate this file: {exc}")
    st.stop()

metric_values = {
    "Accuracy": accuracy_score(y_test, y_pred),
    "AUC": roc_auc_score(y_test, y_score),
    "Precision": precision_score(y_test, y_pred, zero_division=0),
    "Recall": recall_score(y_test, y_pred, zero_division=0),
    "F1": f1_score(y_test, y_pred, zero_division=0),
    "MCC": matthews_corrcoef(y_test, y_pred),
}
st.subheader(f"Results — {selected_model}")
cols = st.columns(6)
for col, (label, value) in zip(cols, metric_values.items()):
    col.metric(label, f"{value:.4f}")

left, right = st.columns([1, 1])
with left:
    st.subheader("Confusion matrix")
    matrix = confusion_matrix(y_test, y_pred, labels=[0, 1])
    fig, ax = plt.subplots(figsize=(5, 4))
    sns.heatmap(matrix, annot=True, fmt="d", cmap="Blues",
                xticklabels=["No", "Yes"], yticklabels=["No", "Yes"], ax=ax)
    ax.set_xlabel("Predicted")
    ax.set_ylabel("Actual")
    st.pyplot(fig)
with right:
    st.subheader("Classification report")
    report = classification_report(
        y_test, y_pred, labels=[0, 1], target_names=["no", "yes"],
        output_dict=True, zero_division=0
    )
    st.dataframe(pd.DataFrame(report).transpose().round(4), use_container_width=True)

st.divider()
st.subheader("Test data preview")
st.write(f"Rows evaluated: **{len(test_df):,}**")
st.dataframe(test_df.head(10), use_container_width=True)
